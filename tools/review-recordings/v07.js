const { record } = require('./lib');
record('07-pages_manage_engagement', 'pages_manage_engagement', async r => {
  const { page } = r;
  await r.caption('A visitor commented on one of the person’s Page posts');
  await r.click(page.getByRole('link', { name: 'Engage', exact: true }).first()); await page.waitForLoadState('networkidle'); await r.pause(1200);
  await r.click(page.getByRole('link', { name: /Comments/ }).first()); await page.waitForLoadState('networkidle'); await r.pause(1200);
  const row = page.locator('main li, main [role=listitem]').filter({ hasText: /Hummm/ }).first();
  await r.click(row); await r.pause(2000);
  await r.caption('1. Reply publicly under the comment, as the Page');
  const box = page.getByPlaceholder(/Write a public reply/).last();
  await r.type(box, 'Merci ! 😊', 70);
  await r.click(page.getByRole('button', { name: /Send reply/ }).last(), 1200);
  await page.locator('main').getByText('Merci ! 😊').first().waitFor({ timeout: 60000 }).catch(() => console.log('reply not shown in thread'));
  await r.pause(1500);
  await r.box(page.locator('main').getByText('Merci ! 😊').first()); await r.pause(3500); await r.unbox();
  await r.caption('2. Hide a comment from public view (the Page can show it again at any time)');
  await r.click(page.getByRole('button', { name: 'Hide comment' }).last(), 1200);
  const confirmHide = page.locator('dialog[open]').last().getByRole('button', { name: /Hide/ });
  if (await confirmHide.count()) await r.click(confirmHide.first());
  const showBtn = page.getByRole('button', { name: /Show comment|Unhide|Show again/ }).last();
  await showBtn.waitFor({ timeout: 60000 }).catch(() => console.log('no show button'));
  await r.pause(1500); await r.box(showBtn); await r.pause(3000); await r.unbox();
  await r.caption('3. Show it again: the comment is public once more');
  await r.click(showBtn, 1200);
  const confirmShow = page.locator('dialog[open]').last().getByRole('button', { name: /Show/ });
  if (await confirmShow.count()) await r.click(confirmShow.first());
  await page.getByRole('button', { name: 'Hide comment' }).last().waitFor({ timeout: 60000 }).catch(() => console.log('hide button not back'));
  await r.pause(2500);
  await r.caption('pages_manage_engagement is used only to let the person reply to, hide and show comments on their own Page');
  await r.pause(4000);
}).catch(e => { console.error(e); process.exit(1); });
