import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { beforeEach, expect, it, vi } from 'vitest';
const deps = vi.hoisted(() => ({ runtime: vi.fn(), client: vi.fn(), targets: vi.fn(), accounts: vi.fn(), keyLimit: 100, session: false, consent: vi.fn() }));
vi.mock('next/headers', () => ({ headers: async () => new Headers(), cookies: async () => ({ get: () => deps.session ? { value: 'synthetic-session' } : undefined }) }));
vi.mock('@/server/auth', () => ({ SESSION_COOKIE: 'session', hashSessionToken: () => 'hash', isUsableSession: () => true }));
vi.mock('@/server/data', () => ({ getSessionByTokenHash: async () => ({}), prisma: { target: { findMany: deps.targets }, adAccount: { findMany: deps.accounts } } }));
vi.mock('@/server/PageFrame', () => ({ PageFrame: ({ children }: { children: React.ReactNode }) => createElement('main', {}, children) }));
vi.mock('@/modules/settings/ui/_components', () => ({ SettingsPanel: ({ children }: { children: React.ReactNode }) => createElement('section', {}, children), styles: {} }));
vi.mock('@/modules/integrations/oauth/server', () => ({ oauthRuntime: deps.runtime, findClient: deps.client }));
vi.mock('@/modules/integrations/oauth/ui/ConsentForm', () => ({ ConsentForm: (props: unknown) => { deps.consent(props); return createElement('form'); } }));
vi.mock('@/server/config/store', () => ({ runtimeConfig: async () => deps.keyLimit }));
vi.mock('@/server/context', () => ({ requireViewer: async () => ({ workspaceId: 'ws1', membership: { role: 'owner', workspace: { name: 'Example workspace' } }, permissions: { pageScope: { all: true } }, entitlements: {} }) }));
vi.mock('@/server/entitlements', () => ({ canUseFeature: () => true, entitledPlatformIds: () => [] }));
vi.mock('@/server/permissions', () => ({ canAccessFeature: () => true }));
vi.mock('@/server/mcp/server', () => ({ workspaceMcpFeatureIds: () => [] }));
vi.mock('@/server/platforms/resource-visibility', () => ({ selectedResourceConnectionWhere: async () => ({}) }));
import { AuthorizeScreen } from '@/modules/integrations/oauth/ui/AuthorizeScreen';
const limits = { enabled: true, issuer: 'https://app.example.test', redirectUriMaxCharacters: 2000, authorizationStateMaxCharacters: 1000, scopeMaxCharacters: 200, resourceIdsMaxItems: 2 };
const params = { client_id: 'oc_AAAAAAAAAAAAAAAAAAAAAAAA', redirect_uri: 'https://client.example.test/cb', response_type: 'code', code_challenge: 'A'.repeat(43), code_challenge_method: 'S256', state: 's'.repeat(1200) };
beforeEach(() => {
  vi.clearAllMocks(); deps.session = false; deps.keyLimit = 100;
  deps.runtime.mockResolvedValue(limits); deps.client.mockResolvedValue({ id: params.client_id, name: 'Example connector', redirectUris: [params.redirect_uri] });
  deps.targets.mockResolvedValue([]); deps.accounts.mockResolvedValue([]);
});
it('refuses over-limit state before looking up or redirecting a client, and honors raised limits', async () => {
  renderToStaticMarkup(await AuthorizeScreen({ searchParams: params }));
  expect(deps.client).not.toHaveBeenCalled();
  deps.runtime.mockResolvedValue({ ...limits, authorizationStateMaxCharacters: 1500 });
  const html = renderToStaticMarkup(await AuthorizeScreen({ searchParams: params }));
  expect(deps.client).toHaveBeenCalledOnce(); expect(html).toContain('href="/sign-in"');
});
it('bounds resource queries by both OAuth and key ceilings without combining separate scopes', async () => {
  deps.session = true; deps.keyLimit = 1;
  deps.targets.mockResolvedValue([{ id: 't1', name: 'Channel' }]); deps.accounts.mockResolvedValue([{ id: 'a1', name: 'Ads' }]);
  renderToStaticMarkup(await AuthorizeScreen({ searchParams: { ...params, state: 'ok' } }));
  expect(deps.targets).toHaveBeenCalledWith(expect.objectContaining({ take: 2 }));
  expect(deps.accounts).toHaveBeenCalledWith(expect.objectContaining({ take: 2 }));
  expect(deps.consent).toHaveBeenLastCalledWith(expect.objectContaining({ truncated: false, channels: [{ id: 't1', name: 'Channel' }], adAccounts: [{ id: 'a1', name: 'Ads' }] }));
  deps.keyLimit = 100;
  deps.targets.mockResolvedValue([{ id: 't1' }, { id: 't2' }, { id: 't3' }]);
  renderToStaticMarkup(await AuthorizeScreen({ searchParams: { ...params, state: 'ok' } }));
  expect(deps.targets).toHaveBeenLastCalledWith(expect.objectContaining({ take: 3 }));
  expect(deps.consent).toHaveBeenLastCalledWith(expect.objectContaining({ truncated: true, channels: [], adAccounts: [] }));
});
