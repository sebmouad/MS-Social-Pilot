const { chromium } = require('playwright');
(async () => {
  const U = 'https://' + new URL(process.env.SP_URL).host;
  const b = await chromium.launch(); const ctx = await b.newContext({ viewport: { width: 1366, height: 900 }, locale: 'en-US' });
  await ctx.request.post(U + '/api/auth/sign-in', { headers: { Origin: U }, data: { email: process.env.SP_USER, password: process.env.SP_PASSWORD } });
  const p = await ctx.newPage(); const slow = [];
  p.on('console', m => { if (m.type() === 'error') console.log('CONSOLE', m.text().slice(0, 200)); });
  p.on('pageerror', e => console.log('PAGEERROR', String(e).slice(0, 200)));
  p.on('requestfinished', async r => { const t = r.timing(); if (t.responseEnd > 2000) slow.push(`${Math.round(t.responseEnd)}ms ${r.method()} ${r.url().replace(U, '').slice(0, 100)}`); });
  p.on('requestfailed', r => console.log('FAILED', r.url().replace(U, '').slice(0, 100), r.failure()?.errorText));
  const t0 = Date.now();
  const resp = await p.goto(U + '/content/feeds', { waitUntil: 'commit', timeout: 120000 }).catch(e => { console.log('goto', String(e).slice(0, 120)); return null; });
  console.log('first byte after', Date.now() - t0, 'ms status', resp && resp.status());
  await p.waitForLoadState('load', { timeout: 120000 }).catch(() => console.log('load event not reached in 120s'));
  console.log('load after', Date.now() - t0, 'ms');
  await p.waitForTimeout(3000);
  console.log('spinners/skeletons:', await p.locator('[aria-busy=true], .ui-skeleton, [role=progressbar]').count(), '| main text:', (await p.locator('main').innerText().catch(() => '')).replace(/\s+/g, ' ').slice(0, 300));
  console.log('slow requests:', slow.slice(0, 8));
  await p.screenshot({ path: 'feeds.png' });
  await b.close();
})();
