export type IntegrationsLocale = keyof typeof integrationsCopy;
export type IntegrationsCopyKey = keyof (typeof integrationsCopy)['en'];

/** `fr` for French-speaking browsers, otherwise English. */
export function integrationsLocale(acceptLanguage: string | null | undefined): IntegrationsLocale {
  return /^\s*fr\b/i.test(acceptLanguage ?? '') ? 'fr' : 'en';
}
export function integrationsText(locale: IntegrationsLocale, key: IntegrationsCopyKey, vars: Record<string, string | number> = {}): string {
  return Object.entries(vars).reduce((text: string, [name, value]) => text.split(`{${name}}`).join(String(value)), integrationsCopy[locale][key]);
}
/** The strings the client component needs, resolved on the server so no copy catalog ships to the browser. */
export function integrationsCopyFor(locale: IntegrationsLocale): Record<IntegrationsCopyKey, string> {
  return { ...integrationsCopy[locale] } as Record<IntegrationsCopyKey, string>;
}
