/**
 * Read-only audit of every legacy table before legacy deletion. Usage (from rebuild/):
 *   npx tsx scripts/legacy-data-audit.ts --sql            print every statement, no database
 *   LEGACY_AUDIT_DATABASE_URL=postgresql://…_rehearsal npx tsx scripts/legacy-data-audit.ts
 * Runs in one server-enforced READ ONLY transaction against a guarded loopback
 * `_preview`/`_rehearsal` database (a restored copy), the same rule as
 * verify-legacy-migration.ts. Output is counts and table names only: never row
 * content. Exit code 1 when a hard failure is found.
 */
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { PrismaClient } from '../generated/client';
import { guardedUrl } from './verify-legacy-migration';
import {
  LEGACY_TABLES, catalogTablesSql, countSql, deleteGate, inboundForeignKeysSql, invalidConstraintsSql,
  isLegacyTable, isRebuildOwned, orphanWorkspaceSql, rebuildDependentsSql, type DeleteGate, type LegacyTable,
} from './legacy-data-manifest';

export type TableReport = {
  table: string; disposition: LegacyTable['disposition']; access: LegacyTable['access']; owner: string;
  present: boolean; rows: string; workspaceOrphans: string | null; gate: DeleteGate; inboundForeignKeys: string[];
};
export type AuditReport = {
  version: 1; ok: boolean; tables: TableReport[]; unclassifiedTables: string[]; missingTables: string[];
  invalidConstraints: string[]; rebuildForeignKeys: string[]; failures: string[];
};

/** Pure decision step, separated so tests can run it without a database. */
export function evaluate(reports: TableReport[], unclassified: string[], invalid: string[]): string[] {
  const failures: string[] = [];
  for (const r of reports) {
    if (r.workspaceOrphans && r.workspaceOrphans !== '0') failures.push(`${r.table}: ${r.workspaceOrphans} rows reference a missing workspace`);
  }
  for (const c of invalid) failures.push(`unvalidated constraint ${c}`);
  for (const u of unclassified) failures.push(`unclassified table ${u}: add it to legacy-data-manifest.ts or rebuild ownership patterns`);
  return failures;
}

export function printSql(): string {
  const lines = ['-- Read-only legacy data verification. Generated by scripts/legacy-data-audit.ts --sql.', 'BEGIN READ ONLY;'];
  lines.push('-- Catalog and constraint checks', `${catalogTablesSql};`, `${invalidConstraintsSql};`, `${rebuildDependentsSql};`);
  for (const e of LEGACY_TABLES) {
    lines.push(`-- ${e.table}: ${e.disposition}`, `${countSql(e.table)};`);
    const orphan = orphanWorkspaceSql(e);
    if (orphan) lines.push(`${orphan};`);
    if (e.disposition !== 'in_place') lines.push(`${inboundForeignKeysSql(e.table)};`);
  }
  lines.push('ROLLBACK;');
  return lines.join('\n') + '\n';
}

export async function auditDatabase(url: string): Promise<AuditReport> {
  const db = new PrismaClient({ datasources: { db: { url: guardedUrl(url) } }, log: [] });
  try {
    return await db.$transaction(async tx => {
      await tx.$executeRawUnsafe('SET TRANSACTION READ ONLY');
      await tx.$executeRawUnsafe("SET LOCAL statement_timeout = '60s'");
      const query = <T>(sql: string) => tx.$queryRawUnsafe<T[]>(sql);
      const present = new Set((await query<{ table_name: string }>(catalogTablesSql)).map(r => r.table_name));
      const tables: TableReport[] = [];
      for (const e of LEGACY_TABLES) {
        const here = present.has(e.table);
        const rows = here ? (await query<{ n: string }>(countSql(e.table)))[0].n : '0';
        const orphanSql = orphanWorkspaceSql(e);
        const orphans = here && orphanSql ? (await query<{ n: string }>(orphanSql))[0].n : null;
        const fks = here ? (await query<{ from_table: string }>(inboundForeignKeysSql(e.table))).map(r => r.from_table) : [];
        tables.push({ table: e.table, disposition: e.disposition, access: e.access, owner: e.owner, present: here, rows,
          workspaceOrphans: orphans, gate: deleteGate(e, Number(rows)), inboundForeignKeys: [...new Set(fks)] });
      }
      const unclassified = [...present].filter(n => !isLegacyTable(n) && !isRebuildOwned(n)).sort();
      const invalid = (await query<{ table_name: string; conname: string }>(invalidConstraintsSql)).map(r => `${r.table_name}.${r.conname}`);
      const rebuildFks = (await query<{ from_table: string; to_table: string }>(rebuildDependentsSql)).map(r => `${r.from_table} -> ${r.to_table}`);
      const failures = evaluate(tables, unclassified, invalid);
      return {
        version: 1 as const, ok: failures.length === 0, tables, unclassifiedTables: unclassified,
        missingTables: tables.filter(t => !t.present).map(t => t.table), invalidConstraints: invalid,
        rebuildForeignKeys: rebuildFks, failures,
      };
    }, { timeout: 120_000 });
  } finally { await db.$disconnect(); }
}

async function main() {
  if (process.argv.includes('--sql')) { process.stdout.write(printSql()); return; }
  const url = process.env.LEGACY_AUDIT_DATABASE_URL;
  if (!url) throw new Error('LEGACY_AUDIT_DATABASE_URL is required.');
  const report = await auditDatabase(url);
  process.stdout.write(JSON.stringify(report, null, 2) + '\n');
  if (!report.ok) process.exitCode = 1;
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  void main().catch(() => {
    process.stdout.write(JSON.stringify({ version: 1, ok: false, error: 'Audit unavailable. Check the guarded loopback URL (_preview or _rehearsal database) and database access.' }) + '\n');
    process.exitCode = 1;
  });
}
